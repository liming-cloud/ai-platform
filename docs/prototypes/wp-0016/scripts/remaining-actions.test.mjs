import test from "node:test";
import assert from "node:assert/strict";
import { createPrototypeStore, createMemoryStorage, DEFAULT_TENANT_ID, PROTOTYPE_STATE_KEY } from "../prototype-state.js";
const actor = "account-qiao";
test("已发布访问策略通过新版本调整，草稿不改变现有权限并且可重复进入", () => {
  const storage = createMemoryStorage();
  const store = createPrototypeStore(storage);
  const policy = store.getSnapshot().accessGovernance.accessPolicies[0];
  const draft = policy.versions.find(item => item.status === "DRAFT");
  store.previewAccessPolicyVersion(draft.id, actor);
  store.publishAccessPolicyVersion(draft.id, actor);
  const members = store.getSnapshot().tenants[0].members;
  assert.equal(store.createAccessPolicyVersion(policy.id, "account-shen").ok, false);
  const result = store.createAccessPolicyVersion(policy.id, actor);
  assert.equal(result.ok, true);
  assert.equal(result.version.status, "DRAFT");
  assert.equal(result.version.preview, null);
  assert.equal(store.createAccessPolicyVersion(policy.id, actor).replayed, true);
  assert.deepEqual(store.getSnapshot().tenants[0].members, members);
  assert.equal(createPrototypeStore(storage).getAccessPolicyProjection(policy.id, actor).version.id, result.version.id);
});
test("更新文档保留来源身份和旧活动版本，不重复新增文档；单文件重建冻结来源版本", () => {
  const storage = createMemoryStorage();
  const store = createPrototypeStore(storage);
  const before = store.getSnapshot().knowledgeBases[0];
  assert.equal(store.replaceKnowledgeSource("kb-handbook", "src-policy-pdf", { mode: "file", name: "policy.exe", sizeMb: 1 }, actor).ok, false);
  const update = store.replaceKnowledgeSource("kb-handbook", "src-policy-pdf", { mode: "paste", name: "年假制度更新", text: "合成的新版本内容" }, actor);
  assert.equal(update.ok, true);
  assert.equal(update.source.revision, "rev-0008");
  assert.equal(update.source.activeRevision, "rev-0007");
  assert.equal(store.getSnapshot().knowledgeBases[0].sources.length, before.sources.length);
  assert.equal(store.getSnapshot().knowledgeBases[0].documents, before.documents);
  assert.equal(store.createIndexRebuild("kb-handbook", { sourceId: "src-policy-pdf" }, actor).ok, false);
  for (let i = 0; i < 6; i += 1) store.advanceKnowledgeSource("kb-handbook", "src-policy-pdf", actor);
  const rebuilt = store.createIndexRebuild("kb-handbook", { sourceId: "src-policy-pdf" }, actor);
  assert.equal(rebuilt.indexVersion.sourceRevision, "rev-0008");
  assert.equal(rebuilt.indexVersion.sourceId, "src-policy-pdf");
  assert.equal(rebuilt.indexVersion.reusedFromIndexId, before.activeIndex);
  assert.equal(store.getSnapshot().knowledgeBases[0].activeIndex, before.activeIndex);
});
test("新组织可以创建自己的路由草稿，但没有可用主备部署不能模拟或发布", () => {
  const store = createPrototypeStore();
  const tenant = store.createTenant({ organizationName: "路由验证组织", tenantCode: "route-demo", administrator: { loginName: 'route.admin', password: 'demo-only', passwordConfirmation: 'demo-only' }, confirmed: true }, 'account-platform-admin').tenant;
  const actor = tenant.administratorAccountId;
  const result = store.createRoutingPolicy(tenant.id, { name: "对话主备路由" }, actor);
  assert.equal(result.ok, true);
  assert.equal(result.policy.tenantId, tenant.id);
  assert.equal(store.simulateRoutingPolicy(result.policy.id, {}, actor).ok, false);
  assert.equal(store.publishRoutingPolicy(result.policy.id, actor).ok, false);
  assert.equal(store.createRoutingPolicy(tenant.id, { name: "对话主备路由" }, actor).reason, "ROUTING_POLICY_NAME_CONFLICT");
});
test("审计目录按当前租户搜索、筛选，非管理员不能读取受控记录", () => {
  const store = createPrototypeStore();
  const all = store.getAuditProjection(DEFAULT_TENANT_ID, actor);
  assert.ok(all.records.length >= 3);
  assert.equal(store.getAuditProjection(DEFAULT_TENANT_ID, actor, { query: "完全不存在" }).records.length, 0);
  assert.ok(store.getAuditProjection(DEFAULT_TENANT_ID, actor, { outcome: "FAILED" }).records.every(item => item.outcome === "FAILED"));
  assert.equal(store.getAuditProjection(DEFAULT_TENANT_ID, "account-shen").ok, false);
  assert.equal(store.getAuditProjection("missing", actor).ok, false);
  assert.doesNotMatch(JSON.stringify(all), /password|objectKey|question|answer|tenantId/);
});
test("访问策略目录可建立独立草稿、选中与刷新，不把新建伪装成已有策略", () => {
  const storage = createMemoryStorage();
  let store = createPrototypeStore(storage);
  const input = { name: "服务组访问", assistantId: "assistant-employee-service", memberAccountIds: ["account-shen"] };
  assert.equal(store.createAccessPolicy(DEFAULT_TENANT_ID, input, "account-shen").ok, false);
  const created = store.createAccessPolicy(DEFAULT_TENANT_ID, input, actor);
  assert.equal(created.ok, true);
  assert.notEqual(created.policy.id, "access-policy-all-employees");
  assert.equal(store.createAccessPolicy(DEFAULT_TENANT_ID, input, actor).reason, "ACCESS_POLICY_NAME_CONFLICT");
  store = createPrototypeStore(storage);
  assert.equal(store.getAccessPolicyProjection(created.policy.id, actor).policy.name, input.name);
  assert.equal(store.selectAccessPolicy(created.policy.id, actor).ok, true);
});
test("批量重试只修改当前知识库失败来源，刷新保持且不可重复重试", () => {
  const storage = createMemoryStorage();
  let store = createPrototypeStore(storage);
  const before = store.getSnapshot().knowledgeBases;
  assert.equal(store.retryFailedKnowledgeSources("kb-handbook", actor).count, 1);
  store = createPrototypeStore(storage);
  const next = store.getSnapshot().knowledgeBases;
  assert.equal(next[0].sources.find(x => x.id === "src-scan-pdf").stage, "EXTRACTING");
  assert.deepEqual(next[1], before[1]);
  assert.equal(next[0].activeIndex, before[0].activeIndex);
  assert.equal(store.retryFailedKnowledgeSources("kb-handbook", actor).reason, "NO_FAILED_SOURCES");
});
test("批量重试越权或存储失败不留下部分结果", () => {
  const memory = createMemoryStorage();
  const store = createPrototypeStore({ ...memory, setItem() { throw Error("合成失败"); } });
  const before = store.getSnapshot();
  assert.equal(store.retryFailedKnowledgeSources("kb-handbook", "account-shen").ok, false);
  assert.equal(store.retryFailedKnowledgeSources("kb-handbook", actor).reason, "STORAGE_UNAVAILABLE");
  assert.deepEqual(store.getSnapshot(), before);
});
test("对象范围登记与来源原子建立，幂等重放可从来源继续安全探测", () => {
  const storage = createMemoryStorage();
  let store = createPrototypeStore(storage);
  const range = store.getObjectStorageScopeProjection(DEFAULT_TENANT_ID, actor).availableRanges[0];
  const input = { tenantId: DEFAULT_TENANT_ID, knowledgeBaseId: "kb-handbook", rangeId: range.id, selectionRevision: range.selectionRevision, name: "受控对象来源" };
  const result = store.registerObjectStorageScope(input, actor);
  assert.equal(result.ok, true);
  let source = store.getSnapshot().knowledgeBases[0].sources.find(x => x.id === result.registration.id);
  assert.equal(source.stage, "RECEIVED");
  assert.equal(source.kind, "对象存储");
  assert.equal(store.registerObjectStorageScope(input, actor).replayed, true);
  assert.equal(store.getSnapshot().knowledgeBases[0].sources.filter(x => x.id === source.id).length, 1);
  store = createPrototypeStore(storage);
  assert.equal(store.advanceKnowledgeSource("kb-handbook", source.id, actor).source.stage, "SCANNING");
  assert.doesNotMatch(storage.getItem(PROTOTYPE_STATE_KEY), /bucket|objectKey|secretKey/);
});
